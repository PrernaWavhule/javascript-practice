// Equality Operator (==) vs Strict Equality Operator (===)

let userName = "Prerna";
let enteredUserName = "PrernaWavhule";
console.log(userName == enteredUserName);

let age = 18;
console.log(age == 18);

let hasPassport = true;
console.log(hasPassport == false);

// Num with Str
console.log(5 == "5");
console.log(5 === "5");

// Bool with Num
console.log(true == 1);
console.log(true === 1);

// Bool with Str
console.log(true == "1");
console.log(true === "1");